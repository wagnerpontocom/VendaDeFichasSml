    private void jComboBox2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox2ActionPerformed
        try {
            int option = jComboBox2.getSelectedIndex();
            LocalDate dataDig = Pandora.STR_LD(jdtDigitacao.getText());
            LocalDate dataVenc = LocalDate.now();

            if (option == 0){
                dataVenc = dataDig;
                jqtParcelas.setText("1");
            } else if (option == 1){ //7
                dataVenc = dataDig.plusDays(7);
                jqtParcelas.setText("1");
            } else if (option == 2){ //10
                dataVenc = dataDig.plusDays(10);
                jqtParcelas.setText("1");
            } else if (option == 3){ //15
                dataVenc = dataDig.plusDays(15);
                jqtParcelas.setText("1");
            } else if (option == 4){ //30
                dataVenc = dataDig.plusDays(30);
                jqtParcelas.setText("1");
            } else if (option == 5){ //30/60
                dataVenc = dataDig.plusDays(30);
                jqtParcelas.setText("2");
            } else if (option == 6){ //30/60/90
                dataVenc = dataDig.plusDays(30);
                jqtParcelas.setText("3");
            }
        
            jdtPrimeiroVenc.setText(Pandora.LD_STR(dataVenc));
            calculaParcelas();
        } catch (Exception ex) {
            Pandora.msgException(ex);
        }
    }//GEN-LAST:event_jComboBox2ActionPerformed

