    private void carregaTabela() {
        DefaultTableModel dm = (DefaultTableModel) jTable1.getModel();
        dm.setNumRows(0);
        
        for (Conta conta : contasGerar) {
            dm.setNumRows(dm.getRowCount()+1);
            if (conta.getQtParcela() == 1){
                dm.setValueAt("1x", dm.getRowCount()-1, 0);
            } else {
                dm.setValueAt(conta.getNrParcela() + "/" + conta.getQtParcela(), dm.getRowCount()-1, 0);
            }
            try {
                dm.setValueAt(Pandora.LD_STR(conta.getDtVencimento()), dm.getRowCount()-1, 1);
            } catch (Exception e) {
            }
            jnf.setValue(conta.getVlDebito());
            dm.setValueAt(jnf.getText(), dm.getRowCount()-1, 2);
            
        }
    }
    
    
    
    private void calculaParcelas(){
        try {
            
            contasGerar = new ArrayList<>();
            
            if (jdtDigitacao.getText().equals("")){
                carregaTabela();
                return;
            }
            if (jdtPrimeiroVenc.getText().equals("")){
                carregaTabela();
                return;
            }
            if (jvlTotal.getValue() == BigDecimal.ZERO){
                carregaTabela();
                //return;
            }
            if (jqtParcelas.getText().equals("")){
                carregaTabela();
                return;
            }
            
            
            LocalDate dtDigitacao = Pandora.STR_LD(jdtDigitacao.getText());
            LocalDate dtPriVenc = Pandora.STR_LD(jdtPrimeiroVenc.getText());
            BigDecimal vlTitulo  = jvlTotal.getValue();
            int qtParc = Integer.parseInt(jqtParcelas.getText());
            BigDecimal qtParcela = BigDecimal.valueOf(qtParc);
        
            
            
            
            
            
            Conta conta;
            double valorParcela = jvlTotal.getValue().doubleValue() / qtParc;
            jnf.setValue(BigDecimal.valueOf(valorParcela));
            valorParcela = jnf.getValue().doubleValue();
            double valorSaldo = jvlTotal.getValue().doubleValue() - (valorParcela*qtParc);
            
            LocalDate dataAux;
            dataAux = Pandora.STR_LD(jdtPrimeiroVenc.getText());
            for (int i = 0; i < qtParc; i++) {
                        
                        
                conta = new Conta();
                conta.setNrParcela(i+1);
                conta.setQtParcela(qtParc);
                conta.setTpMovimento("Entrada");
                conta.setTpSituacao("Aberto");
                conta.setIdPessoa(1L);
                conta.setNmCliConta("WAGNER ALMEIDA SILVEIRA");
                if (dtDigitacao.isEqual(LocalDate.now())){
                    conta.setDtTransacao(LocalDateTime.now());
                } else {
                    conta.setDtTransacao(LocalDateTime.of(dtPriVenc, LocalTime.of(0, 0)));
                }
                //conta.setDtVencimento(LocalDate.now().plusDays(30*(i+1)));
                conta.setDtVencimento(dataAux);
                dataAux = dataAux.plusDays(30);
                
                
                if (i == (qtParc-1)){//ultima parcela (adiconar saldo)
                    conta.setVlDebito(BigDecimal.valueOf(valorParcela + valorSaldo));
                } else {
                    conta.setVlDebito(BigDecimal.valueOf(valorParcela));
                }
                conta.setDsObs(jdsObs.getText());
                conta.setTpOrigem("Manual");
                conta.setInExcluido(false);
                contasGerar.add(conta);
            }
                
            
            
            
        } catch (Exception e) {
            Pandora.ex(e);
        }
        
        carregaTabela();
        
    }

    private void iniciaTela() throws Exception {
        jnf.setVisible(false);
        jtpClassificacao.setVisible(false);
        jlbClassificacao.setVisible(false);
        jdtDigitacao.setText(Pandora.LD_STR(LocalDate.now()));
        jdtPrimeiroVenc.setText(Pandora.LD_STR(LocalDate.now().plusDays(30)));
        jqtParcelas.setText("1");
        jvlTotal.setValue(BigDecimal.ZERO);
        
        calculaParcelas();
        
    }
