    private void atualizaStatus(){
        boolean inLivre = true;
        boolean inFechado = false;
        
        Font f = jLabel1.getFont();
        if (inFechado){
            jLabel1.setText("CAIXA FECHADO");
            jLabel1.setForeground(Color.BLACK);
            jLabel1.setForeground(new Color(234,0,0));
            jLabel1.setFont(f.deriveFont(f.getStyle() | Font.BOLD));
            return;
        }
        
        if (jTableProduto.getRowCount() > 0){
            inLivre = false;
        }
        
        if (!jcdCliente.getText().equals("")){
            inLivre = false;
        }
        
        if (inLivre){
            jLabel1.setText("CAIXA LIVRE");
            jLabel1.setForeground(Color.black);
            //jLabel1.setFont(f.deriveFont(f.getStyle() | ~Font.BOLD));
            jLabel1.setFont(f.deriveFont(f.getStyle() | Font.BOLD));
            
        } else {
            jLabel1.setText("CAIXA OCUPADO");
            jLabel1.setForeground(new Color(204,0,0));
            jLabel1.setFont(f.deriveFont(f.getStyle() | Font.BOLD));
            
        }
    }
    
    
