    private void jNumberLetterField2KeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jNumberLetterField2KeyPressed
        if (evt.getKeyCode() == KeyEvent.VK_ENTER){
            DefaultTableModel dm = (DefaultTableModel) jTableProduto.getModel();
            dm.setRowCount(dm.getRowCount()+1);
            
            dm.setValueAt("  1x", dm.getRowCount()-1, 0);
            //dm.setValueAt(209, dm.getRowCount()-1, 0);
            dm.setValueAt("PRODUTO ESPECIAL PARA COMPRADOR IMPORTANTE", dm.getRowCount()-1, 1);
            dm.setValueAt("", dm.getRowCount()-1, 2);
            dm.setValueAt("R$ 1.290,30", dm.getRowCount()-1, 3);
        } else if (evt.getKeyCode() == KeyEvent.VK_DELETE){
            DefaultTableModel dm = (DefaultTableModel) jTableProduto.getModel();
            if (dm.getRowCount() > 0){
                int opt = JOptionPane.showConfirmDialog(null, "Deseja excluir o último item?");
                if (opt == 0){
                    dm.removeRow(dm.getRowCount()-1);
                    jNumberLetterField2.grabFocus();
                }
                
            }
        } else if (evt.getKeyCode() == KeyEvent.VK_F9){
            jButton1.doClick();
        } else if (evt.getKeyCode() == KeyEvent.VK_F2){
            jButton2.doClick();
        }
        atualizaStatus();
    }//GEN-LAST:event_jNumberLetterField2KeyPressed

    private void jTableProdutoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTableProdutoKeyReleased
        if (jTableProduto.getSelectedRow() >= 0){
            if (evt.getKeyCode() == KeyEvent.VK_DELETE){
                int opt = JOptionPane.showConfirmDialog(null, "Deseja excluir este item?");
                if (opt == 0){
                    DefaultTableModel dm = (DefaultTableModel) jTableProduto.getModel();
                    dm.removeRow(jTableProduto.getSelectedRow());
                    jNumberLetterField2.grabFocus();
                }
            }
        }
    }//GEN-LAST:event_jTableProdutoKeyReleased

